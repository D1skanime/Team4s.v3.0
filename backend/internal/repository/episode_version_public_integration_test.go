type episodePublicQuery struct {
	SQL  string
	Rows int64
}
type episodePublicTracer struct {
	mu      sync.Mutex
	queries []*episodePublicQuery
}
type episodePublicTraceKey struct{}

func (tr *episodePublicTracer) TraceQueryStart(ctx context.Context, _ *pgx.Conn, d pgx.TraceQueryStartData) context.Context {
	q := &episodePublicQuery{SQL: d.SQL}
	tr.mu.Lock()
	tr.queries = append(tr.queries, q)
	tr.mu.Unlock()
	return context.WithValue(ctx, episodePublicTraceKey{}, q)
}
func (tr *episodePublicTracer) TraceQueryEnd(ctx context.Context, _ *pgx.Conn, d pgx.TraceQueryEndData) {
	tr.mu.Lock()
	defer tr.mu.Unlock()
	ctx.Value(episodePublicTraceKey{}).(*episodePublicQuery).Rows = d.CommandTag.RowsAffected()
}
func (tr *episodePublicTracer) reset() { tr.mu.Lock(); defer tr.mu.Unlock(); tr.queries = nil }

