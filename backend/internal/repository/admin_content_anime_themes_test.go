package repository_test

import (
	"context"
	"testing"

	"team4s.v3/backend/internal/models"
	"team4s.v3/backend/internal/repository"
	"team4s.v3/backend/internal/testsupport"

	"github.com/stretchr/testify/require"
)

// TestAdminContentAnimeThemes_ThemeCRUD beweist gegen eine echte, isolierte
// Postgres-Instanz das aktuelle Verhalten des Theme-CRUD-Clusters in
// admin_content_anime_themes.go (ListThemeTypes, ListAdminAnimeThemes,
// CreateAdminAnimeTheme, UpdateAdminAnimeTheme, DeleteAdminAnimeTheme) --
// Characterization Test fuer Plan 174-15 (D-20), damit die Plan-174-18-Aufteilung
// in Theme-CRUD- und Segment-Cluster-Geschwisterdateien ein echtes
// Repository-Ebene-Regressionssignal hat, nicht nur die bisherigen
// Handler-HTTP-Tests bzw. den Segment-Hydrations-Integrationstest.
//
// Skips cleanly when TEAM4S_PHASE117_TEST_DSN is unset.
func TestAdminContentAnimeThemes_ThemeCRUD(t *testing.T) {
	pool := testsupport.OpenPhase117Postgres(t)
	ctx := context.Background()
	repo := repository.NewAdminContentRepository(pool)

	const (
		animeID       = int64(1)
		openingTypeID = int64(1)
		endingTypeID  = int64(2)
		otherAnimeID  = int64(2)
	)
	endingTypeIDVar := endingTypeID

	// The Phase-117 fixture's `themes.id` is a plain BIGINT (every prior fixture
	// consumer supplied explicit IDs). CreateAdminAnimeTheme relies on the real
	// migration's BIGSERIAL auto-increment (database/migrations/0044), so this test
	// -- the first direct CreateAdminAnimeTheme caller against this fixture --
	// restores that identity behavior locally, isolated to this test's own schema.
	_, err := pool.Exec(ctx, `ALTER TABLE themes ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY`)
	require.NoError(t, err)

	_, err = pool.Exec(ctx, `INSERT INTO anime (id) VALUES ($1), ($2)`, animeID, otherAnimeID)
	require.NoError(t, err)
	_, err = pool.Exec(ctx, `INSERT INTO theme_types (id, name) VALUES ($1, 'OP1'), ($2, 'ED1')`, openingTypeID, endingTypeID)
	require.NoError(t, err)

	t.Run("ListThemeTypes gibt beide Seed-Typen geordnet nach ID zurueck", func(t *testing.T) {
		types, err := repo.ListThemeTypes(ctx)
		require.NoError(t, err)
		require.Len(t, types, 2)
		require.Equal(t, models.AdminThemeType{ID: openingTypeID, Name: "OP1"}, types[0])
		require.Equal(t, models.AdminThemeType{ID: endingTypeID, Name: "ED1"}, types[1])
	})

	t.Run("ListAdminAnimeThemes liefert ErrNotFound fuer einen nicht existierenden Anime", func(t *testing.T) {
		_, err := repo.ListAdminAnimeThemes(ctx, int64(999999))
		require.ErrorIs(t, err, repository.ErrNotFound)
	})

	title := "Opening 1"
	created, err := repo.CreateAdminAnimeTheme(ctx, animeID, models.AdminAnimeThemeCreateInput{
		ThemeTypeID: openingTypeID,
		Title:       &title,
	})
	t.Run("CreateAdminAnimeTheme legt ein Theme fuer den Anime an und loest den Typnamen auf", func(t *testing.T) {
		require.NoError(t, err)
		require.NotZero(t, created.ID)
		require.Equal(t, animeID, created.AnimeID)
		require.Equal(t, openingTypeID, created.ThemeTypeID)
		require.Equal(t, "OP1", created.ThemeTypeName)
		require.NotNil(t, created.Title)
		require.Equal(t, title, *created.Title)
	})

	t.Run("CreateAdminAnimeTheme liefert ErrNotFound fuer einen nicht existierenden Anime", func(t *testing.T) {
		_, err := repo.CreateAdminAnimeTheme(ctx, int64(999999), models.AdminAnimeThemeCreateInput{ThemeTypeID: openingTypeID})
		require.ErrorIs(t, err, repository.ErrNotFound)
	})

	t.Run("ListAdminAnimeThemes liefert genau das angelegte Theme, nicht Themes anderer Anime", func(t *testing.T) {
		otherTitle := "Fremdes Theme"
		_, err := repo.CreateAdminAnimeTheme(ctx, otherAnimeID, models.AdminAnimeThemeCreateInput{ThemeTypeID: openingTypeID, Title: &otherTitle})
		require.NoError(t, err)

		themes, err := repo.ListAdminAnimeThemes(ctx, animeID)
		require.NoError(t, err)
		require.Len(t, themes, 1)
		require.Equal(t, created.ID, themes[0].ID)
		require.Equal(t, "OP1", themes[0].ThemeTypeName)
	})

	t.Run("UpdateAdminAnimeTheme aktualisiert Titel und Typ, Aenderung ist nach frischem Read sichtbar", func(t *testing.T) {
		newTitle := "Opening 1 (Clean)"
		err := repo.UpdateAdminAnimeTheme(ctx, created.ID, models.AdminAnimeThemePatchInput{
			ThemeTypeID: &endingTypeIDVar,
			Title:       &newTitle,
		})
		require.NoError(t, err)

		themes, err := repo.ListAdminAnimeThemes(ctx, animeID)
		require.NoError(t, err)
		require.Len(t, themes, 1)
		require.Equal(t, endingTypeID, themes[0].ThemeTypeID)
		require.Equal(t, "ED1", themes[0].ThemeTypeName)
		require.NotNil(t, themes[0].Title)
		require.Equal(t, newTitle, *themes[0].Title)
	})

	t.Run("UpdateAdminAnimeTheme mit leerem Patch ist ein No-Op, solange das Theme existiert", func(t *testing.T) {
		err := repo.UpdateAdminAnimeTheme(ctx, created.ID, models.AdminAnimeThemePatchInput{})
		require.NoError(t, err)
	})

	t.Run("UpdateAdminAnimeTheme auf nicht existierender ID liefert ErrNotFound", func(t *testing.T) {
		missingTitle := "ghost"
		err := repo.UpdateAdminAnimeTheme(ctx, int64(999999), models.AdminAnimeThemePatchInput{Title: &missingTitle})
		require.ErrorIs(t, err, repository.ErrNotFound)
	})

	t.Run("DeleteAdminAnimeTheme entfernt das Theme, danach liefert ListAdminAnimeThemes eine leere Liste", func(t *testing.T) {
		err := repo.DeleteAdminAnimeTheme(ctx, created.ID)
		require.NoError(t, err)

		themes, err := repo.ListAdminAnimeThemes(ctx, animeID)
		require.NoError(t, err)
		require.Empty(t, themes)
	})

	t.Run("DeleteAdminAnimeTheme auf einer bereits geloeschten ID liefert ErrNotFound", func(t *testing.T) {
		err := repo.DeleteAdminAnimeTheme(ctx, created.ID)
		require.ErrorIs(t, err, repository.ErrNotFound)
	})
}
