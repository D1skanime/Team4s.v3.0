// openEpisodeImportReleaseGroupsGuardFixture extends the existing
// openEpisodeImportSourceFixture (the same fixture every other import-apply
// test in this package depends on, see episode_import_repository_apply_test.go/
// episode_import_source_integration_test.go) additively with exactly what the
// Phase-187 Plan-01 dependents guard needs for upsertReleaseVersionGroup: real
// migration 0137 (release_crew_snapshots/release_role_credit_lifecycles) plus
// a trimmed-but-real-column release_version_media stand-in, mirroring
// testsupport.OpenPhase187Postgres's identical rationale. Deliberately does
// NOT switch to the lighter Phase-187 fixture -- upsertReleaseVersionGroup
// also calls lookupAnimeIDByReleaseVersion/lockSegmentAssignmentAnimeTx/
// resolveReleaseVersionEpisodeSortIndexAndVersion/
// autoAssignThemeSegmentsForNewReleaseVersion, all of which need the fuller
// episode/anime/release-graph chain openEpisodeImportSourceFixture already
// provides.
func openEpisodeImportReleaseGroupsGuardFixture(t *testing.T) *pgxpool.Pool {
	t.Helper()
	pool := openEpisodeImportSourceFixture(t)
	ctx := context.Background()

	// Migration 0137 needs point_rules/point_ledger_entries to already exist:
	// it INSERTs seed rows into point_rules (ON CONFLICT (rule_code,
	// rule_version)) and references point_ledger_entries as a nullable FK
	// target for release_role_credit_lifecycles.award_entry_id/
	// reversal_entry_id. openEpisodeImportSourceFixture's Phase-117 base does
	// not create either table (unlike Phase-107, which Plan 01's own fixture
	// builds on and which already has them via migrations 0131-0133). Hand-roll
	// trimmed stand-ins here -- mirroring Plan 01's release_version_media
	// precedent -- with only the shape migration 0137 itself reads/writes, not
	// the full production point_rules/point_ledger_entries schema
	// (database/migrations/0131_member_point_foundation.up.sql). No test in
	// this file inserts a real point_ledger_entries row (every seeded
	// release_role_credit_lifecycles row here stays lifecycle_status='pending',
	// which requires award_entry_id/reversal_entry_id to be NULL), so the
	// trimmed id-only shape is sufficient.
	_, err := pool.Exec(ctx, `
CREATE TABLE point_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_code TEXT NOT NULL,
    rule_version INTEGER NOT NULL,
    category TEXT NOT NULL,
    point_value INTEGER NOT NULL,
    UNIQUE (rule_code, rule_version)
);
CREATE TABLE point_ledger_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
);
`)
	require.NoError(t, err)

	testsupport.ApplySQLFile(t, pool, filepath.Join("..", "..", "..", "database", "migrations", "0137_phase108_contribution_sources.up.sql"))

	// release_version_media: trimmed-but-real-column stand-in, mirrors
	// testsupport.OpenPhase187Postgres's identical rationale -- only the
	// columns countReleaseVersionGroupDependents reads (release_version_id,
	// fansub_group_id, deleted_at). The real, complete column shape lives in
	// database/migrations/0059_release_version_media_schema.up.sql and
	// 0130_release_content_source_groups.up.sql (fansub_group_id column).
	// release_version_notes already exists on openEpisodeImportSourceFixture's
	// Phase-117 base with the same two columns the guard needs, so it is not
	// recreated here.
	_, err = pool.Exec(ctx, `
CREATE TABLE release_version_media (
    id BIGINT PRIMARY KEY,
    release_version_id BIGINT NOT NULL REFERENCES release_versions(id) ON DELETE CASCADE,
    fansub_group_id BIGINT NULL REFERENCES fansub_groups(id) ON DELETE SET NULL,
    category VARCHAR(30) NOT NULL,
    deleted_at TIMESTAMPTZ NULL
);
`)
	require.NoError(t, err)

	return pool
}

// seedUpsertReleaseVersionGroupChain seeds the minimal anime -> episode ->
// fansub_release -> release_version chain upsertReleaseVersionGroup needs
// (lookupAnimeIDByReleaseVersion/lockSegmentAssignmentAnimeTx/
// resolveReleaseVersionEpisodeSortIndexAndVersion all join through it).
// episodes.sort_index/number stay NULL, so
// resolveReleaseVersionEpisodeSortIndexAndVersion resolves a NULL
// episodeSortIndex and autoAssignThemeSegmentsForNewReleaseVersion returns
// immediately without needing any themes/theme_segments rows.
func seedUpsertReleaseVersionGroupChain(t *testing.T, ctx context.Context, pool *pgxpool.Pool, animeID, episodeID, releaseID, releaseVersionID int64) {
	t.Helper()
	_, err := pool.Exec(ctx, `INSERT INTO anime (id) VALUES ($1)`, animeID)
	require.NoError(t, err)
	_, err = pool.Exec(ctx, `INSERT INTO episodes (id, anime_id) VALUES ($1, $2)`, episodeID, animeID)
	require.NoError(t, err)
	_, err = pool.Exec(ctx, `INSERT INTO fansub_releases (id, episode_id) VALUES ($1, $2)`, releaseID, episodeID)
	require.NoError(t, err)
	_, err = pool.Exec(ctx, `INSERT INTO release_versions (id, release_id) VALUES ($1, $2)`, releaseVersionID, releaseID)
	require.NoError(t, err)
}

func importMappingForGroupIDs(groupIDs ...int64) models.EpisodeImportMappingRow {
	inputs := make([]models.SelectedFansubGroupInput, len(groupIDs))
	for i, id := range groupIDs {
		id := id
		inputs[i] = models.SelectedFansubGroupInput{ID: &id}
	}
	return models.EpisodeImportMappingRow{FansubGroups: inputs}
}

// TestUpsertReleaseVersionGroup_GuardBehavior proves the Plan-03 behavior
// table (D-06/D-07/D-12/D-14): the import group-write path must always allow
// a same-group re-apply and a partner-group addition even when the existing
// group(s) have real dependents, must reject an actual group replace that
// would drop a group with real dependents, and must reject reducing an
// existing (>0-group) release to zero groups -- all via the same shared
// diffRemovedReleaseVersionGroupIDs-based guard Plan 02's editor path uses,
// with zero import-specific exception code.
func TestUpsertReleaseVersionGroup_GuardBehavior(t *testing.T) {
	pool := openEpisodeImportReleaseGroupsGuardFixture(t)
	ctx := context.Background()

	t.Run("re-applying the same group is always allowed even with real dependents (D-12 same-group-update)", func(t *testing.T) {
		const (
			animeID          = int64(201)
			episodeID        = int64(211)
			releaseID        = int64(221)
			releaseVersionID = int64(231)
			groupA           = int64(241)
			memberID         = int64(251)
		)
		seedUpsertReleaseVersionGroupChain(t, ctx, pool, animeID, episodeID, releaseID, releaseVersionID)
		_, err := pool.Exec(ctx, `INSERT INTO fansub_groups (id, name, slug) VALUES ($1, 'GroupA', 'guard-201-a')`, groupA)
		require.NoError(t, err)
		_, err = pool.Exec(ctx, `INSERT INTO members (id) VALUES ($1)`, memberID)
		require.NoError(t, err)
		_, err = pool.Exec(ctx, `INSERT INTO release_version_groups (release_version_id, fansub_group_id) VALUES ($1, $2)`, releaseVersionID, groupA)
		require.NoError(t, err)
		_, err = pool.Exec(ctx, `
			INSERT INTO release_role_credit_lifecycles (release_version_id, fansub_group_id, member_id, role_code, generation, lifecycle_status)
			VALUES ($1, $2, $3, 'timing', 1, 'pending')
		`, releaseVersionID, groupA, memberID)
		require.NoError(t, err)

		tx, err := pool.Begin(ctx)
		require.NoError(t, err)
		defer tx.Rollback(ctx)

		mapping := importMappingForGroupIDs(groupA)
		err = upsertReleaseVersionGroup(ctx, tx, releaseVersionID, mapping, models.EpisodeImportMediaCandidate{}, nil)
		require.NoError(t, err)
		require.True(t, releaseVersionGroupExists(t, ctx, tx, releaseVersionID, groupA))
	})

	t.Run("adding a partner group is always allowed even when the existing group has real dependents (D-12 add)", func(t *testing.T) {
		const (
			animeID          = int64(202)
			episodeID        = int64(212)
			releaseID        = int64(222)
			releaseVersionID = int64(232)
			groupA           = int64(242)
			groupB           = int64(243)
			memberID         = int64(252)
		)
		seedUpsertReleaseVersionGroupChain(t, ctx, pool, animeID, episodeID, releaseID, releaseVersionID)
		_, err := pool.Exec(ctx, `INSERT INTO fansub_groups (id, name, slug) VALUES ($1, 'GroupA', 'guard-202-a'), ($2, 'GroupB', 'guard-202-b')`, groupA, groupB)
		require.NoError(t, err)
		_, err = pool.Exec(ctx, `INSERT INTO members (id) VALUES ($1)`, memberID)
		require.NoError(t, err)
		_, err = pool.Exec(ctx, `INSERT INTO release_version_groups (release_version_id, fansub_group_id) VALUES ($1, $2)`, releaseVersionID, groupA)
		require.NoError(t, err)
		_, err = pool.Exec(ctx, `
			INSERT INTO release_role_credit_lifecycles (release_version_id, fansub_group_id, member_id, role_code, generation, lifecycle_status)
			VALUES ($1, $2, $3, 'timing', 1, 'pending')
		`, releaseVersionID, groupA, memberID)
		require.NoError(t, err)

		tx, err := pool.Begin(ctx)
		require.NoError(t, err)
		defer tx.Rollback(ctx)

		mapping := importMappingForGroupIDs(groupA, groupB)
		err = upsertReleaseVersionGroup(ctx, tx, releaseVersionID, mapping, models.EpisodeImportMediaCandidate{}, nil)
		require.NoError(t, err)
		require.True(t, releaseVersionGroupExists(t, ctx, tx, releaseVersionID, groupA))
		require.True(t, releaseVersionGroupExists(t, ctx, tx, releaseVersionID, groupB))
	})

	t.Run("replacing a group that has real dependents with a different group is rejected (D-12 replace-is-guarded)", func(t *testing.T) {
		const (
			animeID          = int64(203)
			episodeID        = int64(213)
			releaseID        = int64(223)
			releaseVersionID = int64(233)
			groupA           = int64(244)
			groupC           = int64(245)
			memberID         = int64(253)
		)
		seedUpsertReleaseVersionGroupChain(t, ctx, pool, animeID, episodeID, releaseID, releaseVersionID)
		_, err := pool.Exec(ctx, `INSERT INTO fansub_groups (id, name, slug) VALUES ($1, 'GroupA', 'guard-203-a'), ($2, 'GroupC', 'guard-203-c')`, groupA, groupC)
		require.NoError(t, err)
		_, err = pool.Exec(ctx, `INSERT INTO members (id) VALUES ($1)`, memberID)
		require.NoError(t, err)
		_, err = pool.Exec(ctx, `INSERT INTO release_version_groups (release_version_id, fansub_group_id) VALUES ($1, $2)`, releaseVersionID, groupA)
		require.NoError(t, err)
		_, err = pool.Exec(ctx, `
			INSERT INTO release_role_credit_lifecycles (release_version_id, fansub_group_id, member_id, role_code, generation, lifecycle_status)
			VALUES ($1, $2, $3, 'timing', 1, 'pending')
		`, releaseVersionID, groupA, memberID)
		require.NoError(t, err)

		tx, err := pool.Begin(ctx)
		require.NoError(t, err)
		defer tx.Rollback(ctx)

		mapping := importMappingForGroupIDs(groupC)
		err = upsertReleaseVersionGroup(ctx, tx, releaseVersionID, mapping, models.EpisodeImportMediaCandidate{}, nil)
		require.Error(t, err)
		require.True(t, errors.Is(err, ErrGroupHasDependents))

		var depErr *GroupHasDependentsError
		require.True(t, errors.As(err, &depErr))
		require.Equal(t, groupA, depErr.FansubGroupID)
		require.True(t, depErr.Summary.HasAny())

		require.True(t, releaseVersionGroupExists(t, ctx, tx, releaseVersionID, groupA), "the dependents-having group's row must survive the rejected replace")
	})

	t.Run("reducing an existing release to zero groups is rejected (D-06/D-14 import half)", func(t *testing.T) {
		const (
			animeID          = int64(204)
			episodeID        = int64(214)
			releaseID        = int64(224)
			releaseVersionID = int64(234)
			groupA           = int64(246)
		)
		seedUpsertReleaseVersionGroupChain(t, ctx, pool, animeID, episodeID, releaseID, releaseVersionID)
		_, err := pool.Exec(ctx, `INSERT INTO fansub_groups (id, name, slug) VALUES ($1, 'GroupA', 'guard-204-a')`, groupA)
		require.NoError(t, err)
		_, err = pool.Exec(ctx, `INSERT INTO release_version_groups (release_version_id, fansub_group_id) VALUES ($1, $2)`, releaseVersionID, groupA)
		require.NoError(t, err)

		tx, err := pool.Begin(ctx)
		require.NoError(t, err)
		defer tx.Rollback(ctx)

		// Explicit empty FansubGroups slice (non-nil) -- resolveImportFansubSelection
		// resolves this to a zero-length memberGroups set, same as the real import
		// apply loop sends when the admin explicitly cleared every group selection.
		mapping := models.EpisodeImportMappingRow{FansubGroups: []models.SelectedFansubGroupInput{}}
		err = upsertReleaseVersionGroup(ctx, tx, releaseVersionID, mapping, models.EpisodeImportMediaCandidate{}, nil)
		require.Error(t, err)
		require.True(t, errors.Is(err, ErrReleaseVersionGroupsEmpty))
		require.True(t, releaseVersionGroupExists(t, ctx, tx, releaseVersionID, groupA), "groupA's row must survive the rejected empty-reduction")
	})
}
