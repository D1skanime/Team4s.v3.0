func hydrationState(t *testing.T,pool *pgxpool.Pool)string {
 t.Helper();var state string
 require.NoError(t,pool.QueryRow(context.Background(),`SELECT jsonb_build_array(
 (SELECT jsonb_agg(to_jsonb(x)) FROM release_versions x),
 (SELECT jsonb_agg(to_jsonb(x)) FROM release_variants x),
 (SELECT jsonb_agg(to_jsonb(x)) FROM release_streams x),
 (SELECT jsonb_agg(to_jsonb(x)) FROM stream_sources x))::text`).Scan(&state));return state
}
