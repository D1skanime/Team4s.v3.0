func TestReleaseMetadataOnlyRejectsSourceSelector(t *testing.T) {
 var input models.EpisodeVersionPatchInput
 require.NoError(t,json.Unmarshal([]byte(`{"title":"A","media_source_id":"source-b"}`),&input))
 require.False(t,isReleaseMetadataOnlyPatch(input))
 valid,message:=validateEpisodeVersionPatchRequest(models.EpisodeVersionPatchInput{MediaSourceID:models.OptionalString{Set:true,Value:hydrationText("source-b")}})
 require.Empty(t,message);require.True(t,valid.MediaSourceID.Set)
 for _,source:=range []*string{nil,hydrationText(""),hydrationText("x,y")} {
  _,message=validateEpisodeVersionPatchRequest(models.EpisodeVersionPatchInput{MediaSourceID:models.OptionalString{Set:true,Value:source}})
  require.NotEmpty(t,message)
 }
}
